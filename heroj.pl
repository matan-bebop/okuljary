на(сам, кишені). множина(кишені).
синоніми(кишені, [кишеня, карман, кармани]).
відмінок(місцевий, кишені, кишенях).
відкрито(кишені). в(кишені, нічого).
можна(відкрити, кишені) :- !, false.

в(кишені, Щось) :- має(Щось).

опис(кишені, ВКишеняхОпис) :-
    має(_Щось),
    bagof(Щ, має(Щ), ЩЩ), atomic_list_concat(ЩЩ, ", ", ВКишенях),
    atomic_list_concat(["Ти носиш з собою таке: ", ВКишенях, "."],
                       ВКишеняхОпис).

дія(0, шарудіти, [шарудіти, пошарудіти, копатися, покопатися, копирсатися, покопирсатися, дослідити, ритися, поритися, досліджувати]).
відмінок_предмета(шарудіти, в, місцевий).
можна(шарудіти, в, Щось) :- можна(зазирнути_в, в, Щось).
шарудіти(Щось) :- зазирнути_в(Щось).


дія(0, інвентар, [інвентар, маю, має, маєш, кишені, кишеня, кармани, карман]).

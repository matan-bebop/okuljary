% Загальне повідомлення на 'взяти щось'
% -------------------------------------
після(взяти(Щось)) :-
    має(Щось), !,
    once(відмінок(знахідний, Щось, КогоЩо)),
    оповідь("Ти кладеш "), оповідь(КогоЩо), оповідь(" до кишені.").



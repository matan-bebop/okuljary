% Допомога
% ========
дія(0, поміч, [поміч, допомога, підказка, підказки, команди, дії, дієслова, плани]).
поміч :-
    абзац("Ти завжди все розрулював сам, і допомога тобі не потрібна. Твоє життя складається переважно з дієслів. От сьогодні, це:"),
    вивести_всі_команди([]).


вивести_всі_команди(ВжеВиведені) :-
    дія(0, _, [Перша|Решта]),
    (Команда = Перша
     ; member(Команда, Решта),
       string_length(Команда, Довжина), Довжина =< 4), % TODO: Де 'диви'?
    \+ memberchk(Команда, ВжеВиведені),
    оповідь(команда, Команда), оповідь(" "),
    вивести_всі_команди([Команда|ВжеВиведені]).
вивести_всі_команди(_ВжеВиведені).


% Сказати
% =======

сказати(Щось) :-
    з_великої_літери(Щось, ЩосьЗВеликої),
    абзац, оповідь(ЩосьЗВеликої), оповідь("—кажеш ти задумливо."), абзац.



% Повний зашквар
% ==============
% В якийсь момент, ти вирішуєш, що треба терміново викликати поліцію. Тоді
% майже на всі дії виводиться повідомлення, що час біжить і треба дзвонити.

можна_зашквареним(abort, [], []).
можна_зашквареним(кінець_гри, [], []).
можна_зашквареним(дзвонити, _, 'Юлька').
можна_зашквареним(дзвонити, _, поліція).
можна_зашквареним(дзвонити, _, швидка).

можна(Дія, _Прийменник, Предмет) :-
        \+ вже(подзвонив_копам), було(до_дії),
	\+ можна_зашквареним(Дія, _, Предмет),  !,
	встановлена_помилка('Треба дзвонити в поліцію.'),
	fail.

сповістити_помилку('Треба дзвонити в поліцію.', Речення) :- !,
    наступний_такт, % тут може і гра скінчитись!
    оповідь("Яке там "), оповідь(Речення), оповідь("?!!"),
    оповідь("Треба дзвонити в поліцію!"),
    поспішай.

поспішай :- раз(1, підганяє), оповідь("Гаєш час на роздуми, а як прийде Юлька, спробуй їй це все поясни!").
поспішай :- раз(2, підганяє), оповідь("Поки ти вагаєшся, час же йде!").
поспішай :- раз(3, підганяє), оповідь("Вже мабуть скоро Юлька прийде…").
поспішай :- раз(4, підганяє), оповідь("Вже скільки часу згаяно…").
поспішай :- раз(5, підганяє), оповідь("Може, це твій останній шанс!").

% Повний зашквар
% ==============
% В якийсь момент, ти вирішуєш, що треба терміново викликати поліцію. Тоді
% на всі дії крім 'дз' виводиться повідомлення, що час біжить і треба дзвонити.

можна(Дія, _Прийменник, Предмет) :-
	Дія \= abort,
        Дія \= дзвонити, Дія \= дзвонити_в_службу, Дія \= дзвонити_на_номер,
        Предмет \= поліція,
        \+ вже(подзвонив_копам), було(до_дії), !,
	встановлена_помилка('Треба дзвонити в поліцію.'),
        наступний_такт,
	fail.

сповістити_помилку('Треба дзвонити в поліцію.', Речення) :- !,
    оповідь("Яке там "), оповідь(Речення), оповідь("?!!"),
    оповідь("Треба дзвонити в поліцію!"),
    поспішай.

поспішай :- раз(1, підганяє), оповідь("Поки ти вагаєшся, час же йде!").
поспішай :- раз(2, підганяє), оповідь("Часу стає все менше і менше!").
поспішай :- раз(3, підганяє), оповідь("Вже мабуть скоро Юлька прийде, тоді ще їй все пояснювати!").
поспішай :- раз(4, підганяє), оповідь("Вже скільки часу згаяно на роздуми…").
поспішай :- раз(5, підганяє), оповідь("Може, це твій останній шанс!").

